def max_chess_board_size(n, m):
    """
    Находит максимальный размер квадратной шахматной доски.
    
    Подход: бинарный поиск по размеру доски
    
    Args:
        n: количество белых плиток
        m: количество черных плиток
    Returns:
        максимальный размер стороны шахматной доски
    """
    
    # ЭТАП 1: Определяем границы для бинарного поиска
    left = 0  # минимальный размер доски
    
    # Максимальный возможный размер: если бы мы могли использовать все плитки
    # В худшем случае все плитки одного цвета, значит максимум sqrt(n+m)
    right = int((n + m) ** 0.5) + 1
    
    print(f"Ищем размер доски в диапазоне [{left}, {right}]")
    
    # ЭТАП 2: Бинарный поиск
    while left < right:
        # Проверяем средний размер (с округлением вверх для поиска максимума)
        mid = (left + right + 1) // 2
        print(f"\nПроверяем размер доски: {mid}×{mid}")
        
        # Общее количество клеток в доске
        total_cells = mid * mid
        print(f"Общее количество клеток: {total_cells}")
        
        # ЭТАП 3: Проверяем, можно ли построить доску размером mid×mid
        can_build = False
        
        if mid % 2 == 0:
            # Четный размер: равное количество белых и черных клеток
            needed_white = total_cells // 2
            needed_black = total_cells // 2
            
            print(f"Четный размер: нужно {needed_white} белых и {needed_black} черных")
            print(f"У нас есть: {n} белых и {m} черных")
            
            can_build = (n >= needed_white and m >= needed_black)
            
        else:
            # Нечетный размер: одного цвета на 1 больше
            needed_min = total_cells // 2      # меньшее количество
            needed_max = total_cells // 2 + 1  # большее количество
            
            print(f"Нечетный размер: нужно {needed_max} одного цвета и {needed_min} другого")
            print(f"У нас есть: {n} белых и {m} черных")
            
            # Проверяем оба варианта распределения цветов:
            # Вариант 1: белых больше (белые в углах)
            variant1 = (n >= needed_max and m >= needed_min)
            # Вариант 2: черных больше (черные в углах) 
            variant2 = (n >= needed_min and m >= needed_max)
            
            print(f"Вариант 1 (белых больше): {variant1}")
            print(f"Вариант 2 (черных больше): {variant2}")
            
            can_build = variant1 or variant2
        
        print(f"Можно построить доску {mid}×{mid}: {can_build}")
        
        # ЭТАП 4: Корректируем границы поиска
        if can_build:
            # Если можем построить доску размером mid, 
            # пробуем найти доску большего размера
            left = mid
            print(f"Обновляем left = {left}")
        else:
            # Если не можем построить доску размером mid,
            # пробуем доску меньшего размера
            right = mid - 1
            print(f"Обновляем right = {right}")
    
    return left


